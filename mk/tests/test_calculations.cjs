const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root,'app.js'),'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(0,source.indexOf('function setData')) + '\nglobalThis.api={makeRows,shiftMonth,quarter,percent,validate,followRange};})();', context);
const {makeRows,shiftMonth,quarter,percent,validate,followRange}=context.api;
assert.equal(shiftMonth('2020-01',-1),'2019-12');
assert.equal(shiftMonth('2020-12',1),'2021-01');
assert.equal(quarter('2020-06'),'2020-04');
assert.equal(percent(null,100),null);
assert.equal(percent(100,0),null);
assert.ok(Math.abs(percent(110,100)-10)<1e-10);
const fixture={series:{}};
for(const k of ['NASDAQ','SP500','QQQ','FEDFUNDS','GS2','GS10','PAYEMS','GDP','GDPC1'])fixture.series[k]={observations:[]};
for(const k of ['NASDAQ','SP500','QQQ'])fixture.series[k].observations=[{date:'2020-01-31',value:100},{date:'2020-02-28',value:110},{date:'2020-04-30',value:90}];
fixture.series.PAYEMS.observations=[{date:'2019-12-01',value:1000},{date:'2020-01-01',value:1200},{date:'2020-02-01',value:1100},{date:'2020-04-01',value:500}];
fixture.series.GDPC1.observations=[{date:'2019-10-01',value:100},{date:'2020-01-01',value:110}];
const rows=makeRows(fixture,'2020-04');
assert.equal(rows.length,4);
assert.equal(rows[0].NFP,200);
assert.equal(rows[1].NFP,-100);
assert.equal(rows[3].NFP,null,'Do not compute payroll changes across a missing month');
assert.equal(rows[2].NASDAQ,null,'Do not forward-fill market prices');
assert.equal(rows[3].NASDAQ_return,null,'Do not compute returns across a missing month');
assert.ok(Math.abs(rows[0].GDP_GROWTH-46.41)<1e-8);
assert.equal(rows[0].GDP_GROWTH,rows[2].GDP_GROWTH,'Quarter value maps only into its own quarter');
assert.equal(rows[3].GDP_GROWTH,null,'Unreleased quarters stay missing');
const real=validate(JSON.parse(fs.readFileSync(path.join(root,'data/history.json'),'utf8')));
assert.ok(makeRows(real).length>=240);
console.log('Calculation checks passed: month boundaries, payroll differences, GDP quarter mapping, missing data, returns.');

const extended=makeRows(fixture,'2020-06');
assert.equal(extended.at(-1).month,'2020-06');
assert.equal(extended.at(-1).NASDAQ,null,'Current month without a quote remains empty');
assert.equal(extended.at(-1).partial,true);
const active={start:'2006-11',end:'2026-10',focus:'2026-10',preset:'20',followNow:true};
const rolled=followRange(active,'2005-01','2026-11');
assert.equal(rolled.start,'2006-12');assert.equal(rolled.end,'2026-11');assert.equal(rolled.focus,'2026-11');
assert.equal(followRange({...active,focus:'2020-04'},'2005-01','2026-11').focus,'2020-04');
assert.equal(followRange({...active,preset:null},'2005-01','2026-11').start,'2006-11');
assert.equal(followRange({...active,followNow:false},'2005-01','2026-11').end,'2026-10');
console.log('Follow-current checks passed: rolling range, fixed range, pinned month, missing current data.');
